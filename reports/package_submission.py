"""Package the code, instructions and derived summaries without private caches."""

from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "output/ISYE4031_Group9_Milestone2_Code.zip"


def main():
    files = [ROOT / name for name in [
        "README.md", "MILESTONE2_README.md", "requirements.txt", "requirements-milestone2.txt",
        ".env.example", ".gitignore", "run_pipeline.py", "run_milestone2.py", "audit_kaggle.py", "data/README.md",
    ]]
    for folder, pattern in [("src", "*.py"), ("tests", "*.py"), ("notebooks", "*.ipynb"),
                            ("reports", "*.py"), ("reports", "*.md"),
                            ("figures/milestone2", "*.png"),
                            ("outputs/milestone2", "*.csv"), ("outputs/milestone2", "*.json")]:
        files.extend(sorted((ROOT / folder).glob(pattern)))
    # These event-level tables remain available locally and are regenerated by code.
    files = [p for p in files if p.name not in {"baseline_predictions.csv", "training_influence.csv", "build_report.py"}]
    # Verify local credential values do not appear in any packaged file.
    secrets = []
    if (ROOT / ".env").exists():
        for line in (ROOT / ".env").read_text(encoding="utf-8-sig").splitlines():
            if line.strip().startswith("ALPHA_VANTAGE_API_KEY="):
                value = line.partition("=")[2].strip().strip("\"'")
                if value and value != "YOUR_KEY_HERE":
                    secrets.append(value.encode())
    for p in files:
        assert p.exists(), p.name
        assert not any(secret in p.read_bytes() for secret in secrets), "Credential found in candidate file; packaging stopped"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(OUTPUT, "w", ZIP_DEFLATED) as archive:
        for p in sorted(set(files)):
            archive.write(p, "ISYE4031_Earnings_Project/" + p.relative_to(ROOT).as_posix())
    with ZipFile(OUTPUT) as archive:
        assert archive.testzip() is None
        assert all("/data/raw/" not in name and "/data/processed/" not in name
                   and "/.venv/" not in name and not name.endswith("/.env") for name in archive.namelist())
        print(f"Packaged {len(archive.namelist())} files; excluded credentials, environments and original vendor observations.")
    print(OUTPUT)


if __name__ == "__main__":
    main()
